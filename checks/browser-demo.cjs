const { chromium } = require('../client-tools/node_modules/playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const out = __dirname;
let browser;
(async () => {
  browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-dev-shm-usage', '--no-sandbox'] });
  const errors = [];
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  const a = await context.newPage();
  a.on('pageerror', e => errors.push(String(e)));
  a.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const url = process.env.DEMO_URL || 'http://localhost:2567';
  await a.goto(url, { waitUntil: 'domcontentloaded' });
  await a.waitForFunction(() => window.templeDemo?.world, { timeout: 120000 });
  await a.screenshot({ path: path.join(out, '01-入院.png') });
  await a.locator('#nickname').fill('演示主持');
  await a.locator('#enter').click();
  await a.waitForFunction(() => window.templeDemo?.room?.state?.players?.size >= 1, { timeout: 15000 });
  await a.waitForTimeout(1000);
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  const b = await mobile.newPage();
  b.on('pageerror', e => errors.push(String(e)));
  await b.goto(url, { waitUntil: 'domcontentloaded' });
  await b.waitForFunction(() => window.templeDemo?.world, { timeout: 120000 });
  await b.locator('#nickname').fill('同游访客'); await b.locator('#enter').click();
  await a.waitForFunction(() => window.templeDemo.room.state.players.size === 2, { timeout: 15000 });
  await b.waitForFunction(() => window.templeDemo.room.state.players.size === 2, { timeout: 15000 });
  await b.waitForTimeout(3300);
  const before = await a.evaluate(() => { const p=window.templeDemo.localPosition; return { x:p.x,z:p.z }; });
  await a.keyboard.down('KeyA'); await a.waitForTimeout(1000); await a.keyboard.up('KeyA'); await a.waitForTimeout(500);
  const after = await a.evaluate(() => { const p=window.templeDemo.localPosition; return { x:p.x,z:p.z }; });
  assert.ok(Math.hypot(after.x-before.x,after.z-before.z)>.5,'keyboard moved local player');
  const actorId = await a.evaluate(() => window.templeDemo.room.sessionId);
  await b.waitForFunction(({id,x,z}) => {const p=window.templeDemo.room.state.players.get(id);return p&&Math.hypot(p.x-x,p.z-z)<.2;}, {id:actorId,...after});
  await a.screenshot({ path: path.join(out, '02-多人庙院.png') });
  await b.screenshot({ path: path.join(out, '03-手机同游.png') });
  await a.locator('#overview').click(); await a.waitForTimeout(1000);
  await a.screenshot({ path: path.join(out, '04-院落全景.png') });
  const report={ testedAt:new Date().toISOString(), engine:'Cocos Creator 3.8.8', browser:'Chrome headless / software WebGL', actualPhones:false, actualPublicHosting:false, clients:2, desktopViewport:'1440x900', mobileViewport:'390x844', joined:true, remoteMovementReceived:true, movement:{before,after}, errors };
  fs.writeFileSync(path.join(out,'browser-report.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
  await browser.close();
  if(errors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();});
